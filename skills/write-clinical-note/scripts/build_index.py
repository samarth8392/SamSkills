"""Build references/dsm5tr/INDEX.md and references/dsm5tr/index.json from note front-matter.

Usage: python scripts/build_index.py references/dsm5tr
"""
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

import yaml

ROOT = Path(sys.argv[1]).resolve()
CHAPTERS = ROOT / "chapters"
FM = re.compile(r"^---\n(.*?)\n---\n", re.S)


def norm(s):
    return re.sub(r"\s+", " ", str(s).strip().lower())


entries, problems = [], []
for path in sorted(CHAPTERS.rglob("*.md")):
    if path.name == "_coverage.md":
        continue
    rel = path.relative_to(ROOT).as_posix()
    m = FM.match(path.read_text())
    if not m:
        if not path.name.startswith("_"):
            problems.append(f"no front-matter: {rel}")
        continue
    try:
        fm = yaml.safe_load(m.group(1)) or {}
    except yaml.YAMLError as e:
        problems.append(f"bad YAML: {rel}: {str(e).splitlines()[0]}")
        continue
    if not isinstance(fm, dict) or "name" not in fm:
        problems.append(f"missing name: {rel}")
        continue
    as_list = lambda k: [str(x) for x in (fm.get(k) or [])] if isinstance(fm.get(k), list) else ([str(fm[k])] if fm.get(k) else [])
    cnum = path.parent.name.split('-')[0]
    kind = ("overview" if path.name.startswith('_') else
            "research" if cnum == "29" else
            "alternative-model" if cnum == "28" else
            "topic" if cnum in {"01", "24", "25", "26", "27"} else
            "diagnostic-reference")
    entries.append({
        "name": str(fm["name"]),
        "file": rel,
        "chapter": str(fm.get("chapter", path.parent.name)),
        "chapter_dir": path.parent.name,
        "pdf_pages": str(fm.get("pdf_pages", "")),
        "icd10": as_list("icd10"),
        "aliases": as_list("aliases"),
        "key_features": as_list("key_features"),
        "differentials": as_list("differentials"),
        "specifiers": as_list("specifiers"),
        "min_duration": str(fm.get("min_duration", "") or ""),
        "age_notes": str(fm.get("age_notes", "") or ""),
        "kind": kind,
        "source_edition": "DSM-5-TR (APA, 2022)",
        "overview": path.name.startswith("_"),
    })

if problems:
    for problem in problems:
        print("PROBLEM:", problem, file=sys.stderr)
    sys.exit(1)

by_name = {norm(e["name"]): e for e in entries}
for e in entries:
    for a in e["aliases"]:
        by_name.setdefault(norm(a), e)


def link(name, base=""):
    e = by_name.get(norm(name))
    return f"[{name}]({e['file']})" if e else name


dx = [e for e in entries if not e["overview"]]
out = ["# DSM-5-TR Study Index", "",
       "Auto-generated by `scripts/build_index.py` — do not hand-edit; rebuild after changing notes.", "",
       "**How to use:** find a disorder below (A–Z, by code, or by feature), open its note, then check "
       "its *Differential diagnosis* and *Documentation cues* sections. Chapter overviews explain how "
       "neighbouring disorders are told apart. Page numbers are PDF pages of "
       "`references/source/DSM 5 TR-APA (2022).pdf`.", "",
       "**Use limits:** these are study summaries of the 2022 edition, not independently clinically "
       "validated notes or a current billing-code source. Code lookup includes codes discussed in a "
       "note (including exclusions and associated conditions), so read its Coding section before use. "
       "Section III proposed conditions and the alternative personality model are labeled separately "
       "in index.json. Topic notes are included in the A–Z lookup. See [agent guidance](AGENT_GUIDE.md) "
       "and [progress](PROGRESS.md).", "",
       "- [Chapters](#chapters)", "- [Disorders A–Z](#disorders-az)", "- [Lookup by ICD-10-CM code](#lookup-by-icd-10-cm-code)",
       "- [Lookup by feature / symptom](#lookup-by-feature--symptom)", "- [Aliases](#aliases)",
       "- Reference tables: [alphabetical codes](reference/icd10-codes-alphabetical.md) · [numerical codes](reference/icd10-codes-numerical.md) · [classification navigation and source discrepancies](reference/classification-navigation.md)", ""]
out += ["- Original-source navigation: [classification](../source/dsm5tr_text/00-dsm-5-tr-classification.md) · "
        "[book subject index](../source/dsm5tr_text/supplement-book-index.md). "
        "Subject-index references use printed book pagination, not PDF page positions.", ""]

out += ["## Chapters", ""]
chapters = defaultdict(list)
for e in entries:
    chapters[e["chapter_dir"]].append(e)
for cdir in sorted(chapters):
    items = chapters[cdir]
    ov = sorted(f for f in (CHAPTERS / cdir).glob("_overview*.md"))
    title = next((e["chapter"] for e in items if e["chapter"]), cdir)
    ovlinks = " · ".join(f"[{p.stem.lstrip('_')}](chapters/{cdir}/{p.name})" for p in ov)
    out.append(f"### {title}")
    if ovlinks:
        out.append(f"Overview: {ovlinks}  ")
    out.append(", ".join(f"[{e['name']}]({e['file']})" for e in sorted(items, key=lambda e: e["file"]) if not e["overview"]))
    out.append("")

out += ["## Disorders A–Z", "", "| Disorder / topic | Reference kind | ICD-10-CM references | Min. duration | Chapter | PDF pp. | Key differentials |", "|---|---|---|---|---|---|---|"]
for e in sorted(dx, key=lambda e: norm(e["name"])):
    diffs = ", ".join(link(d) for d in e["differentials"][:6])
    codes = ", ".join(e["icd10"][:8]) + (" …" if len(e["icd10"]) > 8 else "")
    out.append(f"| [{e['name']}]({e['file']}) | {e['kind']} | {codes} | {e['min_duration']} | {e['chapter']} | {e['pdf_pages']} | {diffs} |")
out.append("")

out += ["## Lookup by ICD-10-CM code", "", "| Code | Note(s) |", "|---|---|"]
codes = defaultdict(set)
for e in dx:
    for c in e["icd10"]:
        codes[c.strip()].add((e["name"], e["file"]))
for c in sorted(codes):
    out.append(f"| {c} | " + "; ".join(f"[{n}]({f})" for n, f in sorted(codes[c])) + " |")
out.append("")

out += ["## Lookup by feature / symptom", "",
        "Features as tagged in each note's front-matter. Use this to build a differential from presenting symptoms.", ""]
feats = defaultdict(set)
for e in dx:
    for k in e["key_features"]:
        feats[norm(k)].add((e["name"], e["file"]))
for k in sorted(feats):
    out.append(f"- **{k}** — " + ", ".join(f"[{n}]({f})" for n, f in sorted(feats[k])))
out.append("")

out += ["## Aliases", ""]
for e in sorted(dx, key=lambda e: norm(e["name"])):
    if e["aliases"]:
        out.append(f"- {', '.join(e['aliases'])} → [{e['name']}]({e['file']})")
out.append("")

(ROOT / "INDEX.md").write_text("\n".join(out))
(ROOT / "index.json").write_text(json.dumps(entries, indent=1))
unresolved = sorted({d for e in dx for d in e["differentials"] if norm(d) not in by_name})
print(f"{len(dx)} notes, {len(chapters)} chapters, {len(codes)} codes, {len(feats)} features")
print(f"{len(unresolved)} differential names without a matching note (shown unlinked)")
for p in problems:
    print("PROBLEM:", p)
